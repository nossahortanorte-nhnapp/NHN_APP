// lib/api.js
import axios from 'axios';

export const fetchProfiles = async () => {
  try {
    const response = await axios.get('http://localhost:8000/api/v1/profile/s/');
    return response.data;
  } catch (error) {
    console.error('Erro ao buscar hortas:', error);
    return [];
  }
};
